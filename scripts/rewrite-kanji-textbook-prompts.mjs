function chooseContext(material, index) {
  const word = material.word;
  const fixed = special.get(word);
  if (fixed) return fixed;
  if (/[ぁ-ゖ]/u.test(word)) {
    if (/(?:い|だ)$/u.test(word)) return adjectiveTemplate;
    return verbTemplate;
  }
  return nounTemplates[index % nounTemplates.length];
}

let rewritten = 0;
for (const [index, material] of source.materials.entries()) {
  if (material.promptBefore !== "教科書に「" || material.promptAfter !== "」と書いてあります。") continue;
  const [promptBefore, promptAfter] = chooseContext(material, index);
  material.promptBefore = promptBefore;
  material.promptAfter = promptAfter;
  rewritten += 1;
}

for (const material of source.materials) {
  const correction = corrections.get(material.pairId);
  if (correction) {
    [material.promptBefore, material.promptAfter] = correction;
  }
}

await writeFile(sourcePath, `${JSON.stringify(source, null, 2)}\n`, "utf8");
