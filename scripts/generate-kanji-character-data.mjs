import { access, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = JSON.parse(await readFile(resolve(projectRoot, "content-source/kanji-materials.json"), "utf8"));
const characters = [...new Set(source.materials
  .filter((material) => material.reviewStatus === "approved")
  .flatMap((material) => material.targetKanji))].sort((left, right) => left.localeCompare(right, "ja"));
const packageRoot = resolve(projectRoot, "node_modules/@jamsch/hanzi-writer-data-jp");

for (const character of characters) {
  try {
    await access(resolve(packageRoot, `${character}.json`));
  } catch {
    throw new Error(`承認済み問題の日本語ストロークデータがありません: ${character}`);
  }
}

const imports = characters.map((character, index) =>
  `import character${index} from "@jamsch/hanzi-writer-data-jp/${character}.json";`,
).join("\n");
const entries = characters.map((character, index) => `  ${JSON.stringify(character)}: character${index} as CharacterJson,`).join("\n");
const output = `// Generated by scripts/generate-kanji-character-data.mjs. Do not edit directly.\nimport type { CharacterJson } from "hanzi-writer";\n${imports}\n\nexport const generatedCharacterData: Record<string, CharacterJson> = {\n${entries}\n};\n`;
const outputPath = resolve(projectRoot, "src/generated/kanjiCharacterData.ts");
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, output, "utf8");
console.log(`generated ${outputPath} (${characters.length} characters)`);
